"""Task 2 offline comparison against immutable Task 1. Standard library only.

No acquisition, production imports, subprocesses or network. Run --check to
verify generated bytes; Task 1 files are hash-checked and never written.
"""
import argparse
from collections import Counter
import copy
import csv
import hashlib
import importlib.util
import io
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BASE = ROOT.parent
REPO = BASE.parents[1]
spec = importlib.util.spec_from_file_location("task1_calibration", BASE / "calibrate.py")
policy = importlib.util.module_from_spec(spec)
spec.loader.exec_module(policy)
BASELINE = "b62f00de56b2f1aa488e9f41742b86617efcec72"


def read(path):
    return json.loads(path.read_text(encoding="utf-8"))


def verify_baseline():
    manifest = read(ROOT / "inputs/baseline-manifest.json")
    if manifest["commit"] != BASELINE:
        raise ValueError("Wrong Task 1 baseline")
    for name, digest in manifest["files"].items():
        if hashlib.sha256((REPO / name).read_bytes()).hexdigest() != digest:
            raise ValueError("Task 1 packet changed: " + name)
    return manifest


def audience_group(ratings):
    """Only the unchanged paired archive batch is comparable in this packet.

    No invented age/coverage threshold. Indexed/absent halves and heterogeneous
    observations cannot enter the archival audience comparison.
    """
    expected = read(BASE / "inputs/historical-ratings.json")
    if all(o.get("status") == "archived"
           and o.get("source_url") == expected["provenance"]["url"]
           and o.get("available_by") == expected["available_by"]
           and o.get("rating") is not None and o.get("votes") is not None
           for o in ratings.values()) and set(ratings) == set(policy.SCALES):
        return "task1_paired_archival_batch"
    return None


def competition_ranks(values):
    # Ties share a rank; the next rank skips the tied positions.
    return {iid: 1 + sum(v > value + 1e-9 for v in values.values())
            for iid, value in values.items()}


def validate_evidence(evidence, baseline):
    identities = {f["imdb_id"]: f for f in baseline["films"]}
    if evidence["task"] != 2 or evidence["ratings"] or evidence["extensions_added"]:
        raise ValueError("This packet retains baseline ratings and extension evidence")
    for fact in evidence["awards"]:
        identity = identities[fact["imdb_id"]]
        source = evidence["sources"][fact["source_id"]]
        if (fact["tmdb_id"] != identity["tmdb_id"]
                or fact["film_title"] != identity["title"]
                or fact["unique_film_attribution"] is not True
                or fact["source_url"] != source["source_url"]
                or not fact["source_url"].startswith("https://")
                or fact["verification"] != source["access_method"]
                or fact["event_year"] is None
                or fact["observed_at"] != evidence["research_date"]):
            raise ValueError("Unbound award attribution/provenance")
        policy.recognition([fact])  # Reject unmodeled types/statuses.
    allowed = {"verified_positive", "verified_no_award", "unavailable", "not_yet_announced"}
    for check in evidence["coverage_checks"]:
        if (check["status"] not in allowed or not check["scope"] or not check["components"]
                or not set(check["imdb_ids"]) <= identities.keys()
                or any(policy.POLICY[k][1] != check["venue"] for k in check["components"])):
            raise ValueError("Invalid scoped coverage check")
        if check["status"] == "verified_no_award" and check["verification"] != "primary_page_via_web":
            raise ValueError("Absence needs a checked primary category/edition list")
        for fact in evidence["awards"]:
            if (check["status"] == "verified_no_award"
                    and fact["imdb_id"] in check["imdb_ids"]
                    and fact["component"] in check["components"]
                    and fact["event_year"] == check["event_year"]):
                raise ValueError("Positive fact contradicts scoped absence")


def calculate():
    manifest = verify_baseline()
    baseline = read(BASE / "results.json")
    evidence = read(ROOT / "inputs/observations.json")
    validate_evidence(evidence, baseline)
    if policy.SCENARIOS != {"unsmoothed": 0, "modest": 1000, "stronger": 10000}:
        raise ValueError("Smoothing policy drift")
    films = []
    upgrades = 0
    for old in baseline["films"]:
        iid = old["imdb_id"]
        additions = [r for r in evidence["awards"] if r["imdb_id"] == iid]
        records = [r for c in old["award_breakdown"]["components"].values() for r in c["evidence"]]
        records += additions
        awards = policy.recognition(records)
        improved = []
        for component, value in awards["components"].items():
            previous = old["award_breakdown"]["components"].get(component, {})
            direct_before = any(r["verification"] == "primary_web_observation"
                                for r in previous.get("evidence", []))
            direct_now = any(r["verification"] == "primary_page_via_web"
                             for r in value["evidence"])
            if direct_now and not direct_before:
                improved.append(component)
        upgrades += len(improved)
        variants = {}
        for scenario, strength in policy.SCENARIOS.items():
            audience = {s: policy.audience_component(o, s, strength)
                        for s, o in old["ratings"].items()}
            observed = sum(c["points"] for c in audience.values() if c["points"] is not None)
            paired = all(c["points"] is not None for c in audience.values())
            for extension, requested in policy.EXTENSIONS.items():
                enabled = sorted(set(requested) & {e["kind"] for e in old["extension_evidence"]})
                points = policy.recognition(records, enabled)["observed_points"]
                total = policy.rounded(observed + sum(points.values()))
                key = scenario + "/" + extension
                previous = old["variants"][key]
                variants[key] = {
                    "prior_strength": strength, "audience_components": audience,
                    "audience_points": observed if paired else None,
                    "observed_audience_subtotal": observed,
                    "signed_smoothing_delta": sum(c["adjustment_points"] for c in audience.values()
                                                  if c["adjustment_points"] is not None),
                    "recognition_observed_points": points,
                    "recognition_family_scores": {f: v if v == policy.FAMILIES[f] else None
                                                  for f, v in points.items()},
                    "recognition_subtotal": sum(points.values()),
                    "conditional_observed_subtotal": total,
                    "evidence_delta_vs_task1_same_variant": total - previous["provisional_observed_subtotal"],
                    "audience_evidence_delta_vs_task1": policy.rounded(observed) - previous["observed_audience_subtotal"],
                    "recognition_evidence_delta_vs_task1": policy.rounded(sum(points.values())) - previous["recognition_subtotal"],
                    "overall_score": None, "overall_rank": None,
                    "status": "conditional_mixed_age_incomplete", "enabled_extensions": enabled,
                    "missing_audience_capacity": 25 * sum(c["points"] is None for c in audience.values()),
                    "unverified_recognition_capacity": sum(policy.FAMILIES[f] - v for f, v in points.items()),
                    "audience_only_rank": None, "audience_rank_change_vs_unsmoothed": None,
                    "audience_rank_change_vs_task1": None,
                }
        coverage = copy.deepcopy(old["coverage"])
        for family, venues in coverage.items():
            for venue, entry in venues.items():
                fresh_checks = [c for c in evidence["coverage_checks"]
                                if iid in c["imdb_ids"] and c["venue"] == venue]
                entry["task2_checks"] = fresh_checks
                # Preserve original coverage; a scoped check never certifies a whole family.
                entry["task2_review_status"] = ("positive_evidence_partial" if any(
                    policy.POLICY[r["component"]][1] == venue for r in additions) else
                    "checked_scoped" if any(c["status"].startswith("verified_") for c in fresh_checks) else
                    "not_yet_announced" if fresh_checks and all(c["status"] == "not_yet_announced" for c in fresh_checks) else
                    "unavailable" if fresh_checks else "source_not_checked")
        films.append({"imdb_id": iid, "tmdb_id": old["tmdb_id"], "title": old["title"],
                      "year": old["year"], "stratum": old["stratum"],
                      "identity": {k: old[k] for k in ("tmdb_url", "wikidata_url", "tmdb_page_title", "tmdb_release_events")},
                      "identity_change": None, "notes": old["notes"],
                      "ratings": old["ratings"], "ratings_changed_vs_task1": False,
                      "rating_metadata": {s: {"baseline_observation_reference": "../results.json#" + iid + "/ratings/" + s,
                                             "task2_fresh_observation": False,
                                             "retrieved_at": None, "source_measurement_at": o.get("measurement_date"),
                                             "time_precision_limit": "Task 1 has day precision or only available-by date; exact original retrieval time unavailable. Task 2 performed no new rating acquisition.",
                                             "count_precision_limit": "Integer as archived/indexed; upstream rounding/weighting not independently established.",
                                             "access_method": "inherited_public_repository_archive" if o["status"] == "archived" else "inherited_search_index" if o["status"] == "indexed_observation" else "no_usable_observation",
                                             "refresh_status": "stale_measurement_time_unknown" if o.get("rating") is not None else "unavailable"}
                                          for s, o in old["ratings"].items()},
                      "audience_comparison_group": audience_group(old["ratings"]),
                      "coverage": coverage, "award_breakdown": awards,
                      "task2_award_facts": additions, "components_upgraded_to_direct_primary_review": improved,
                      "extension_evidence": old["extension_evidence"], "variants": variants})
    rank_sets = {}
    for scenario in policy.SCENARIOS:
        rank_sets[scenario] = competition_ranks({f["imdb_id"]: f["variants"][scenario + "/base"]["audience_points"]
                                               for f in films if f["audience_comparison_group"]})
    previous_ranks = baseline["diagnostics"]["archive_paired_audience_comparison"]["ranks"]
    for film in films:
        iid = film["imdb_id"]
        if film["audience_comparison_group"]:
            for key, v in film["variants"].items():
                scenario = key.split("/")[0]
                v["audience_only_rank"] = rank_sets[scenario][iid]
                # Positive = moves up; no ranks for partial/indexed rows.
                v["audience_rank_change_vs_unsmoothed"] = rank_sets["unsmoothed"][iid] - rank_sets[scenario][iid]
                v["audience_rank_change_vs_task1"] = previous_ranks[scenario][iid] - rank_sets[scenario][iid]
    return policy.rounded({
        "schema_version": 2, "task": 2, "research_date": evidence["research_date"],
        "baseline_commit": manifest["commit"], "policy": baseline["policy"],
        "input_sha256": {p.name: hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted((ROOT / "inputs").glob("*.json"))},
        "comparison_scope": "22 unchanged paired archival observations only for audience ranks; two indexed IMDb-only controls excluded. No fresh or complete overall leaderboard.",
        "diagnostics": {"film_count": len(films), "years": dict(Counter(f["year"] for f in films)),
                        "ratings": {s: dict(Counter(f["ratings"][s]["status"] for f in films)) for s in policy.SCALES},
                        "fresh_rating_pairs": {s: 0 for s in policy.SCALES},
                        "complete_current_overall_scores": 0,
                        "task2_award_fact_count": len(evidence["awards"]),
                        "task2_award_verification": dict(Counter(r["verification"] for r in evidence["awards"])),
                        "components_upgraded_to_direct_primary_review": upgrades,
                        "task2_coverage_check_statuses": dict(Counter(c["status"] for c in evidence["coverage_checks"])),
                        "audience_comparison_film_count": len(rank_sets["unsmoothed"]),
                        "audience_ranks": rank_sets}, "films": films})


def fmt(value, places=3):
    return "unknown" if value is None else f"{value:.{places}f}"


def render_csv(result):
    stream = io.StringIO(newline="")
    writer = csv.writer(stream, lineterminator="\n")
    source_fields = [f"{s}_{k}" for s in policy.SCALES for k in
                     ("raw_rating", "votes", "adjusted_rating", "points", "smoothing_delta", "status")]
    writer.writerow(["imdb_id", "tmdb_id", "title", "year", "scenario", "extension", *source_fields,
                     *policy.FAMILIES, "audience", "observed_audience_subtotal", "smoothing_delta",
                     "conditional_observed_subtotal", "evidence_delta_vs_task1", "audience_group",
                     "audience_only_rank", "rank_change_vs_unsmoothed", "rank_change_vs_task1",
                     "overall_score", "overall_rank", "status"])
    for f in result["films"]:
        for key, v in f["variants"].items():
            source_values = []
            for s in policy.SCALES:
                o, a = f["ratings"][s], v["audience_components"][s]
                source_values += [o.get("rating"), o.get("votes"), a["adjusted_rating"], a["points"], a["adjustment_points"], o["status"]]
            writer.writerow([f["imdb_id"], f["tmdb_id"], f["title"], f["year"], *key.split("/"),
                             *source_values, *v["recognition_observed_points"].values(), v["audience_points"],
                             v["observed_audience_subtotal"], v["signed_smoothing_delta"], v["conditional_observed_subtotal"],
                             v["evidence_delta_vs_task1_same_variant"], f["audience_comparison_group"],
                             v["audience_only_rank"], v["audience_rank_change_vs_unsmoothed"],
                             v["audience_rank_change_vs_task1"], None, None, v["status"]])
    return stream.getvalue()


def render_comparison(result):
    lines = ["# Task 2 fixed-evidence comparison — " + result["research_date"], "",
             "Generated offline. Audience ranks compare **22 unchanged archival pairs only**. They describe",
             "the pinned observations, not current audience preference. Two sparse IMDb-only controls have no rank.",
             "All overall scores/ranks remain null. EU/Indie/US/Critics below are observed contributions,",
             "not complete measured family values. TIFF and screenplay are off in this base table.", "",
             "Rank triples and Audience triples are m=0 / 1,000 / 10,000. Positive rank change means moving up.", "",
             "| Film | IMDb / TMDb | Audience 0 / 1k / 10k | Audience ranks | EU / Indie / US / Critics | Evidence delta vs Task 1 |",
             "| --- | --- | --- | --- | --- | ---: |"]
    for f in result["films"]:
        variants = [f["variants"][s + "/base"] for s in policy.SCENARIOS]
        points = " / ".join(fmt(v, 1) for v in variants[0]["recognition_observed_points"].values())
        lines.append(f"| {f['title']} | {f['imdb_id']} / {f['tmdb_id']} | " +
                     " / ".join(fmt(v["audience_points"]) for v in variants) + " | " +
                     " / ".join(str(v["audience_only_rank"] or "—") for v in variants) +
                     f" | {points} | {fmt(variants[0]['evidence_delta_vs_task1_same_variant'])} |")
    for f in result["films"]:
        lines += ["", "## " + f["title"], "",
                  f"IMDb {f['imdb_id']} / TMDb {f['tmdb_id']}; {f['year']} premiere stratum `{f['stratum']}`.",
                  f"[Identity mapping]({f['identity']['wikidata_url']}) · [TMDb release context]({f['identity']['tmdb_url']}).",
                  "Baseline identity unchanged; release events: " + ", ".join(e["startDate"] for e in f["identity"]["tmdb_release_events"]) + ".", ""]
        lines += ["Retained Task 1 context (original claims/dates, not new Task 2 additions):", ""]
        lines += [note for note in f["notes"]]
        for s, o in f["ratings"].items():
            lines += ["", f"{s}: raw {o.get('rating')} / {o.get('votes')} votes; `{o['status']}`; "
                      f"[baseline source]({o['source_url']}). Measurement date {o.get('measurement_date')}; "
                      "no Task 2 rating retrieval. Original exact time and upstream precision unavailable."]
        lines += ["", "| m | Adjusted IMDb / LB | Source points IMDb / LB | Signed Audience delta | Base conditional subtotal | TIFF / screenplay / both subtotal |",
                  "| ---: | --- | --- | ---: | ---: | --- |"]
        for s, m in policy.SCENARIOS.items():
            v = f["variants"][s + "/base"]
            a = v["audience_components"]
            lines.append(f"| {m} | " + " / ".join(fmt(a[p]["adjusted_rating"], 6) for p in policy.SCALES) +
                         " | " + " / ".join(fmt(a[p]["points"]) for p in policy.SCALES) +
                         f" | {v['signed_smoothing_delta']:+.3f} | {v['conditional_observed_subtotal']:.3f} | " +
                         " / ".join(fmt(f["variants"][s + "/" + e]["conditional_observed_subtotal"])
                                    for e in ("tiff", "screenplay", "both")) + " |")
        lines += ["", f"Task 2 reviewed award annotations: {len(f['task2_award_facts'])}; components upgraded to direct primary review: " +
                  (", ".join(f["components_upgraded_to_direct_primary_review"]) or "none") + ".",
                  "Task 1 retained facts and all per-component normalized points appear in `results.json` and [Task 1 breakdowns](../breakdowns.md).", ""]
        for fact in f["task2_award_facts"]:
            lines.append(f"- {fact['category']}: {fact['status']}, edition {fact['event_year']}, "
                         f"date {fact['event_date']} ({fact['event_date_kind']}); `{fact['verification']}`; "
                         f"[verification]({fact['source_url']}); observed {fact['observed_at']}.")
        for e in f["extension_evidence"]:
            lines.append(f"- Separate candidate `{e['kind']}`: [retained Task 1 evidence]({e['source_url']}); original observation {e['observed_at']}, not reverified today.")
        lines += ["", "Task 2 venue coverage (a check concerns only its named category/edition):", ""]
        for family, venues in f["coverage"].items():
            lines.append("- " + family + ": " + "; ".join(v + "=" + c["task2_review_status"] for v, c in venues.items()))
            for venue, c in venues.items():
                for check in c["task2_checks"]:
                    lines.append(f"  - {venue}: `{check['status']}` — {check['scope']}; [source]({check['source_url']}).")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = calculate()
    outputs = {"results.json": json.dumps(result, indent=2, ensure_ascii=False, allow_nan=False) + "\n",
               "comparison.csv": render_csv(result), "breakdowns.md": render_comparison(result)}
    for name, content in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_bytes() != content.encode():
                parser.exit(1, "Stale Task 2 output: " + name + "\n")
        else:
            path.write_bytes(content.encode())
    print(("Checked" if args.check else "Generated") + " Task 2: 24 films, 288 variants; offline, Task 1 preserved.")


if __name__ == "__main__":
    main()
